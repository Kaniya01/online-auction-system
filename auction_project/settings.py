def validate_hostname(hostname, setting_name):
    """Validate one DNS name or IP literal (including Django's .domain form)."""
    hostname = hostname.strip()
    if not hostname or hostname == '*' or any(char in hostname for char in '/\\?#@'):
        raise ImproperlyConfigured(f'{setting_name} contains an invalid host.')
    candidate = hostname[1:] if hostname.startswith('.') else hostname
    try:
        parsed = urlsplit(f'http://{candidate}')
        host = parsed.hostname
        if not host or parsed.netloc != candidate or parsed.path or parsed.query or parsed.fragment:
            raise ValueError
        if ':' in host:
            import ipaddress
            ipaddress.ip_address(host)
        elif not all(
            re.fullmatch(r'[A-Za-z0-9](?:[A-Za-z0-9-]{0,61}[A-Za-z0-9])?', label)
            for label in host.rstrip('.').split('.')
        ):
            raise ValueError
    except ValueError as exc:
        raise ImproperlyConfigured(f'{setting_name} contains an invalid host.') from exc
    return hostname


